from enum import Enum


class ExitReason(Enum):
    """退出原因枚举类
    
    定义了任务或进程退出的不同原因类型。这个枚举用于标识任务结束的具体原因，
    有助于系统进行错误处理、日志记录和状态跟踪。
    
    与其他枚举类不同，此类只继承Enum而不继承str，表示这些值主要用于内部逻辑判断。
    """

    INTENTIONAL = 'intentional'
    """意图性退出
    
    表示任务或进程是按照预期计划正常退出的。这包括：
    - 任务成功完成后的正常结束
    - 用户主动停止任务
    - Agent执行FINISH或STOP Action导致的退出
    这是最常见的正常退出情况。
    """

    INTERRUPTED = 'interrupted'
    """被中断的退出
    
    表示任务或进程在执行过程中被外部因素中断。这包括：
    - 用户强制终止任务
    - 系统调度导致的任务中断
    - 网络连接中断导致的任务暂停
    - 资源不足导致的强制停止
    这种退出通常是非预期的，但不一定表示错误。
    """

    ERROR = 'error'
    """错误导致的退出
    
    表示任务或进程因为错误或异常而被迫退出。这包括：
    - 代码执行异常
    - 系统错误
    - 资源访问失败
    - 网络超时错误
    - 配置错误
    这种退出表示存在需要修复的问题。
    """